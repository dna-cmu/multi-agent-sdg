def get_targets_for_goal(goal_number: int) -> list[dict]:
    """Get all targets for a specific SDG goal."""
    prefix = f"{goal_number}."
    targets = []
    for target_id, description in SDG_TARGETS.items():
        if target_id.startswith(prefix) or target_id.startswith(f"{goal_number}."):
            targets.append({"id": target_id, "description": description})
    return sorted(targets, key=lambda t: t["id"])
