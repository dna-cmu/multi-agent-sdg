CREDIBILITY_SCORING_PROMPT_V4 = """You will assess ONE claim from a corporate sustainability report.

WHAT YOU ARE MEASURING
Substantiation: how much the report gives a reader (an analyst or investor, an assurer, a regulator, civil society or media, a lender) to check the claim and hold the company to it. You are NOT judging whether the claim is true, whether the company really did it, or whether it contributes to an SDG. A fully substantiated claim could still be false; a true claim could be unsubstantiated. Score only what is disclosed.
Use only the text given below. Do not use outside knowledge about the company, news or ratings. Do not judge intent; words such as greenwashing or symbolic are not scores and must not appear in your answer.

=== CLAIM ===
Claim text: "{claim_text}"
Location: [Section: {section}, p. {page}]
SDG targets already assigned: {sdg_targets}

=== EVIDENCE PACK ===
S1 and S2 come from the SAME section of the report as the claim. X1, X2 and X3 come from OTHER sections (cross-section). Each passage starts with its [Section: ..., p. ...] tag. "(no passage retrieved)" means the retrieval found nothing for that slot; it is information about the report, not an error.

S1: {S1}

S2: {S2}

X1: {X1}

X2: {X2}

X3: {X3}

=== HOW TO WORK (in this order) ===
Step 1. Score S, M and T from the CLAIM TEXT ONLY. Do not read the evidence pack for these three.
Step 2. Score E from the claim together with ALL passages S1, S2, X1, X2, X3. E is about the quality of the evidence, not the number of passages.
Step 3. Give EVERY passage that has text exactly one label (definitions below). Give "None" to empty slots.
Scores are whole numbers 0, 1, 2 or 3 - no halves, no blanks. If you cannot decide between two scores, choose the LOWER one and say so in the rationale.
Score each dimension on its own rubric; a strict score on one dimension must not make you stricter or more lenient on another.

=== S - SPECIFICITY (claim text only) ===
Question: how specific is the claim about what is being done, by or for whom, and where?
0 = A general statement; no identifiable issue or action. (e.g., "we are committed to sustainability")
1 = Names the issue or action, but no named programme, no specific place or site, and no defined scope. (e.g., "reducing emissions", "employee wellbeing", "reporting emissions")
2 = Names the issue or action AND ONE of: a named programme or project / a specific target area or site / a defined scope (group, community, business unit, population covered). (e.g., "safety training at the Rayong plant" names the topic and the site but not the programme)
3 = Names the issue or action AND a named programme AND a specific target area or defined scope. (e.g., "Supplier Code of Conduct training for all Tier 1 suppliers")
Note: numbers (e.g., "500 employees") belong to M. A number never raises S.

=== M - MEASURABILITY (claim text only) ===
Question: how far is the claim quantified?
0 = No indicator and no language of change; a plain statement.
1 = Words that express change (increase, reduce, improve, worsen) but no number. (e.g., "enhance", "improve", "strengthen", "significant reduction", "increased substantially", "more than last year")
2 = At least one number, but no comparator: no baseline and no target. (e.g., "reduced emissions by 15%" - 15% of what?)
3 = A KPI with a baseline and a target, or a number with its unit and a complete comparator. (e.g., "reduce Scope 1 GHG from 50,000 to 35,000 tCO2e")

=== T - TEMPORALITY (claim text only) ===
Question: does the claim state a point in time or a period?
0 = No time reference. (e.g., "we are committed to...", "we focus on...")
1 = Vague time, OR the claim says something has been done or achieved but gives no date. (e.g., "in the near future", "ongoing", "regularly", "over the coming years", "has been installed", "completed", "achieved")
2 = One specific time point (a start or an end). (e.g., "in FY2024", "by 2030", "during Q3 2024")
3 = Two or more time points, or interim milestones, that allow progress to be tracked (base year and target year, or target year and interim milestones). (e.g., "reduce 20% by 2025, 50% by 2028, net zero by 2030")
Note: "completed / achieved / installed" without a date = 1, not 0. A single deadline ("by 2030") = 2. T = 3 needs at least two trackable time points.

=== E - EVIDENCE (claim + all passages S1, S2, X1-X3) ===
Question: for this claim's data, does the report state how it was obtained, a source, a standard, or external assurance or certification?
0 = Bare assertion: no supporting information and no source.
1 = Self-reported with figures, but no method of collection and no source; OR a standard is named without its number, scope or data location. (e.g., "our satisfaction score was 4.2" with no survey method; "aligned with GRI" with nothing else)
2 = Discloses the method of data collection or analysis, the reporting scope, the source of the data, or conformity with a standard that is identified by its number or scope or by where the data sit in the report. (e.g., sample size, measurement protocol, standard number such as GRI 305 or GRI 305-1, calculation method)
3 = Assured or certified by an external body, with the assuring or certifying organisation named, or the named assurance/certification standard applied to THIS data. (e.g., "assured by Deloitte"; named certification such as ISO 14064 tied to this claim's data)
Notes for E:
- A standard named without its number (e.g., "in line with GRI") = 1. It rises to 2 if at least one of these is given: (a) the scope of the data or the standard's number - what the data cover, e.g. the specific disclosure (GRI 305 or GRI 305-1), the units or areas covered (all plants in Thailand), or the period (2024); or (b) where the data are in the report - page, table, or the GRI content index entry for these data.
- "Independently verified" or "verified by a third party" WITHOUT naming the organisation = 2.
- A named assurer (audit firm, certification body) or a named certification standard (e.g., ISO 14064) that is tied to the data of THIS claim = 3.
- Evidence that is not in the claim text or in the evidence pack must not be used.

=== PASSAGE LABELS (one per passage; compare the passage with the claim's SPECIFIC content: its numbers, named programme, scope or area, target, dates) ===
Extend      = The passage gives information that supports the claim AND is verifiable fact - e.g., the same figure in a data table, or details of the named project (its scope, area, dates or method).
Redundant   = The passage repeats the claim word for word or paraphrases it, adding no information.
Related     = Same topic or same SDG, but the passage does not address what this claim specifically states.
Unrelated   = Not related to the claim.
Contradicts = The passage conflicts with the claim's specific content - e.g., a different number for the same indicator and period; "zero waste to landfill" while a landfill quantity other than zero is reported; different target years in different sections (2030 vs 2035); conflicting scope ("all sites" vs "two pilot sites").
None        = The slot is empty ("(no passage retrieved)").
Rules for labels:
- Judge by content, not by length or by how many words are repeated.
- If undecided between Extend and Redundant, ask: "Does this passage give anything beyond the claim itself?" If not, choose Redundant and say why.
- Label S1 and S2 as well as X1-X3. (Only X1-X3 labelled Extend are later counted for corroboration; you do not count anything.)
Worked example. Claim: "Reduced water use at the Rayong plant by 12% in 2024 against the 2022 base year."
  Extend: environmental data table "Water use, Rayong plant: 2022 = 1.25 million m3; 2024 = 1.10 million m3" (gives the figures to check the 12%).
  Redundant: executive summary "In 2024 we cut water use by 12%" (repeats, adds no fact).
  Related: "The company places importance on sustainable water management" (same topic, not the 12% at Rayong).
  Unrelated: "The company trained 1,200 employees in safety".
  Contradicts: "The Rayong plant reduced water use by 8% in 2024 compared with 2022" (different figure for the same indicator and period).

=== OUTPUT ===
Return ONLY this JSON object, with a one- or two-sentence rationale for each score and a short reason for each label:
{{
  "S": {{"score": 0, "rationale": "..."}},
  "M": {{"score": 0, "rationale": "..."}},
  "T": {{"score": 0, "rationale": "..."}},
  "E": {{"score": 0, "rationale": "..."}},
  "labels": {{
    "S1": {{"label": "Extend|Redundant|Related|Unrelated|Contradicts|None", "reason": "..."}},
    "S2": {{"label": "...", "reason": "..."}},
    "X1": {{"label": "...", "reason": "..."}},
    "X2": {{"label": "...", "reason": "..."}},
    "X3": {{"label": "...", "reason": "..."}}
  }},
  "comment": "Only if you hesitated between two scores, the passages were unhelpful, or the claim text looks truncated or merged; otherwise an empty string."
}}"""
